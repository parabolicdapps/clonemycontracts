export const COSMWASM_CONTAINER: ContainerConfig = {
  host: DEFAULT_CONTAINER.host,
  workRoot: DEFAULT_CONTAINER.workRoot,
  image: process.env.CMC_COSMWASM_IMAGE ?? 'cmc-toolchain-cosmwasm:0.2',
  cpus: 4, memory: '8g', concurrency: 2, timeoutMs: 25 * 60_000,
};

const WARM_APP = new URL('../../../../../toolchains/cosmwasm/runner-warm-app/', import.meta.url);
/** the stub `app` crate that run-plan links when no custom code exists (template path) */
function warmApp(): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (dir: string, base: string) => { for (const e of readdirSync(dir)) { if (e === 'target' || e === 'Cargo.lock') continue; const p = join(dir, e); if (statSync(p).isDirectory()) walk(p, base); else out[p.slice(base.length + 1)] = readFileSync(p, 'utf8'); } };
  walk(WARM_APP.pathname, WARM_APP.pathname.replace(/\/$/, ''));
  return out;
}

export class CosmWasmPack implements TargetPack<CwDesign> {
  readonly id = 'cosmwasm';
  readonly label = 'CosmWasm (Rust, cosmwasm-std 2.2)';
  readonly language = 'Rust (CosmWasm)';
  readonly reportLabels = { runtime: 'a local CosmWasm runtime (cw-multi-test)', template: 'the cw20-base / cw721-base reference contract with an instantiate message', model: 'model-generated CosmWasm contract (messages, storage, errors, events, helpers and entry points are generated by code; the model wrote the handler bodies)', deployTitle: 'Deploy to a CosmWasm testnet' };
  describeNonPortable(spec: ContractSpec) {
    const d = buildDesign(spec);
    return [...d.notTranslated.map((n) => ({ id: n.feature, title: n.feature, where: n.where.split(/,\s*/), detail: n.reason, treatment: 'not-translated' as const })),
      ...spec.nonPortable.filter((n) => ['block.timestamp', 'native-value', 'uint256', 'dynamic-bytes', 'fallback'].includes(n.id)).map((n) => ({ ...n, treatment: 'mapped' as const, detail: ({ 'block.timestamp': 'env.block.time (seconds), `now(&env)`', 'native-value': 'msg.value is the attached amount of the configured native denom; sending value is BankMsg::Send', uint256: 'Uint256 (uint8..32 keep their width, 33..64 u64/Uint64, 65..128 Uint128)', 'dynamic-bytes': 'bytes become Binary (base64 on the wire)', fallback: 'receive() becomes an explicit Deposit message; there is no fallback entry point' } as Record<string, string>)[n.id] ?? n.detail }))];
  }
  constructor(private container: ContainerConfig = COSMWASM_CONTAINER) {}

  design(spec: ContractSpec, opts: { decimals?: number }): CwDesign { return buildDesign(spec, opts.decimals !== undefined ? { originalDecimals: opts.decimals } : {}); }

  templates(spec: ContractSpec, opts: { decimals?: number; facts?: TokenFacts }): TemplateResult<CwDesign> | null {
    const v = classifyStandard(spec);
    if (!v.match) return null;
    const info = cw20Info(spec, v.match);
    const design = buildTemplateDesign(spec, v.match, info);
    const files = recipeFiles(spec, v.match, design, info, opts.facts ?? {});
    return { design, files, standard: v.match.standard, needsProgram: false, buildRun: (set) => (v.match!.standard === 'ERC-20' ? buildCw20Plan({ spec, design, set }, info) : null) };
  }

  units(design: CwDesign): string[] { return design.instructions.filter((h) => !h.generated).map((h) => h.unit); }

  generatePrompt(ctx: GenerateContext<CwDesign>, unit: string) {
    const h = ctx.design.instructions.find((x) => x.unit === unit)!;
    return { system: SYSTEM, user: handlerPrompt(ctx.spec, ctx.design, h, sourceLookup(ctx.sources)) };
  }

  assemble(spec: ContractSpec, design: CwDesign, bodies: Record<string, string>) { return assembleProject(spec, design, bodies); }

  async compile(files: Record<string, string>, onLog?: (s: string) => void): Promise<CompileResult> {
    const r = await runToolchain(this.container, 'compile', files, { wantOut: true, ...(onLog ? { onLog } : {}) });
    const artifacts: Record<string, Buffer> = {};
    if (r.out['app.wasm']) artifacts['app.wasm'] = r.out['app.wasm']!;
    return { ok: r.code === 0 && !!artifacts['app.wasm'], log: r.log, seconds: r.seconds, artifacts };
  }

  blame(log: string, design: CwDesign) { const f = failingHandlers(log, design); return { units: f.handlers, other: f.other || f.handlers.size === 0 }; }

  repairPrompt(design: CwDesign, unit: string, body: string, log: string) {
    const h = design.instructions.find((x) => x.unit === unit)!;
    const blocks = firstErrorBlocks(log, 12, 20000).split(/\n\n(?=error)/).filter((b) => b.includes(`handlers/${unit}.rs`));
    const text = blocks.length ? blocks.slice(0, 4).join('\n\n') : firstErrorBlocks(log, 4, 5000);
    return { system: SYSTEM, user: repairPrompt(h, body, text, hintsFor(text)) };
  }

  behaviourRepairPrompt(design: CwDesign, unit: string, body: string, problems: string[]) {
    return { system: SYSTEM, user: behaviourRepairPrompt(design.instructions.find((x) => x.unit === unit)!, body, problems) };
  }

  unitOf(design: CwDesign, fn: string): string | null {
    if (fn === 'receive') return design.instructions.find((h) => h.solidity === 'receive')?.unit ?? null;
    if (fn === 'constructor') return 'instantiate';
    const h = design.instructions.find((x) => x.solidity === fn && !x.generated);
    return h?.unit ?? null;
  }

  async runScenarios(files: Record<string, string>, _compiled: CompileResult, design: CwDesign, spec: ContractSpec, set: ScenarioSet): Promise<ScenarioRun> {
    const t0 = Date.now();
    let built; let project: Record<string, string>;
    if (design.mode === 'template') {
      const t = this.templates(spec, {})!;
      built = t.buildRun(set) as ReturnType<typeof buildCw20Plan> | null;
      if (!built) {
        const outcomes = set.scenarios.map((s) => ({ id: s.id, title: s.title, kind: s.kind, ...(s.fn ? { fn: s.fn } : {}), status: 'not-runnable' as const, mismatches: [], notRunnable: ['the cw721-base recipe is not executed by this pipeline'], checked: 0, notes: [] }));
        return { outcomes, seconds: 0, conformance: [] };
      }
      project = { ...warmApp(), 'cmc/plan.json': JSON.stringify(built.plan) };
    } else {
      built = buildProgramPlan({ spec, design, set });
      project = { ...files, 'cmc/plan.json': JSON.stringify(built.plan) };
    }
    const r = await runToolchain(this.container, 'run-plan', project, {});
    const res = extractResult(r.log) as RunnerResult | null;
    if (!res) return { outcomes: [], seconds: (Date.now() - t0) / 1000, fatal: `the runner produced no result (exit ${r.code}): ${r.log.slice(-800)}`, conformance: [] };
    return { outcomes: compareResults(set, built, res, design), seconds: (Date.now() - t0) / 1000, conformance: [] };
  }

  deployCommands(design: CwDesign, spec: ContractSpec): string[] {
    if (design.mode === 'template') return ['bash deploy-testnet.sh   # needs a chain CLI (neutrond/wasmd/osmosisd), a funded testnet key and the cw20_base.wasm / cw721_base.wasm reference build (not executed here)'];
    return [
      '# build the optimized wasm (reproducible): docker run --rm -v "$PWD":/code cosmwasm/optimizer:0.16.0   (or: cargo build --release --target wasm32-unknown-unknown with Rust 1.81)',
      'cosmwasm-check artifacts/app.wasm',
      '# testnet example (Neutron pion-1; any wasmd chain works, replace CLI, node, chain id, fees):',
      'CLI=neutrond; NODE=https://rpc-palvus.pion-1.ntrn.tech:443; CHAIN_ID=pion-1; FROM=<your testnet key>',
      'FLAGS="--node $NODE --chain-id $CHAIN_ID --from $FROM --gas auto --gas-adjustment 1.4 --fees 5000untrn -y -o json"',
      '$CLI tx wasm store artifacts/app.wasm $FLAGS      # note the code_id from the store_code event',
      `$CLI tx wasm instantiate <CODE_ID> '<InstantiateMsg JSON, see project/src/msg.rs${design.native.used ? '; native_denom = "untrn"' : ''}>' --label ${snake(spec.name)} --admin $($CLI keys show $FROM -a) $FLAGS`,
      `# token calls: the contract pulls cw20 with TransferFrom, so first: $CLI tx wasm execute <CW20_ADDR> '{"increase_allowance":{"spender":"<APP_ADDR>","amount":"<N>"}}' $FLAGS`,
      `# ${spec.name}: not audited`,
    ];
  }
}
