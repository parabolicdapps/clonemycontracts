import { ell, more } from '../../pipeline/report.js';
import type { ContractSpec, ScenarioSet, TokenFacts } from '../../types.js';
import { classifyStandard } from '../../spec/standard.js';
import { DEFAULT_CONTAINER, extractResult, runToolchain, type ContainerConfig } from '../../pipeline/container.js';
import type { CompileResult, GenerateContext, ScenarioRun, TargetPack, TemplateResult } from '../pack.js';
import { buildProgramPlan, buildTokenPlan, MOCK_MODULE, type RunnerResult } from './adapter.js';
import { DEF_FILE, genProject, parseUnits, stubUnits } from './codegen.js';
import { compareResults } from './compare.js';
import { buildDesign } from './design.js';
import type { TezosDesign } from './design-types.js';
import { formatIssues, lintBody, normaliseBody } from './lint.js';
import { SYSTEM, behaviourRepairPrompt, handlerPrompt, hintsFor, parseUnitSections, repairPrompt, sourceLookup } from './prompts.js';
import { buildTemplateDesign, erc20Info, genFa12Module, recipeFiles, recipeFits, type Erc20Info } from './template.js';

export const TEZOS_CONTAINER: ContainerConfig = {
  host: DEFAULT_CONTAINER.host,
  workRoot: DEFAULT_CONTAINER.workRoot,
  image: process.env.CMC_TEZOS_IMAGE ?? 'cmc-toolchain-tezos:0.2',
  cpus: 2, memory: '8g', concurrency: 2, timeoutMs: 10 * 60_000, // 8g: the SmartPy compiler is an x86_64 binary; under arm64 emulation (qemu) it is OOM-killed with a 4g-6g limit
};

const MOCK_INFO: Erc20Info = { nameParam: -1, symbolParam: -1, supplyParam: null, decimals: 18, mintable: true, burnable: false, ownable: false, increaseAllowance: false, decreaseAllowance: false, renounce: false, zeroGuards: false, approveGuard: false };

/** `=== UNIT x ===` sections for compile() logs */
const section = (unit: string, text: string) => `=== UNIT ${unit} ===\n${text.trim()}\n`;

export class TezosPack implements TargetPack<TezosDesign> {
  readonly id = 'tezos';
  readonly label = 'Tezos (SmartPy 0.25.3 -> Michelson)';
  readonly language = 'SmartPy (compiles to Michelson)';
  readonly reportLabels = { runtime: 'the SmartPy simulator (the same engine that runs `sp.test_scenario`)', template: 'a generated FA1.2 (TZIP-7) token contract compiled with SmartPy', model: 'model-generated SmartPy contract (the module, storage, signatures, helpers, checks and views of public state are generated by code; the model wrote the function bodies)', deployTitle: 'Originate on Ghostnet (not executed)' };
  /** body normalisations applied by `assemble` (unit -> fixes), for the report notes */
  readonly normalisations = new Map<string, string[]>();
  constructor(private container: ContainerConfig = TEZOS_CONTAINER) {}

  describeNonPortable(spec: ContractSpec) {
    const d = buildDesign(spec);
    return [...d.notTranslated.map((n) => ({ id: n.feature, title: n.feature, where: n.where.split(/,\s*/), detail: n.reason, treatment: 'not-translated' as const })),
      ...spec.nonPortable.filter((n) => ['block.timestamp', 'native-value', 'uint256', 'dynamic-bytes', 'fallback'].includes(n.id)).map((n) => ({ ...n, treatment: 'mapped' as const, detail: ({ 'block.timestamp': '`self.now_secs()` (seconds as a nat, from sp.now)', 'native-value': 'msg.value is the attached amount in mutez as a nat, NOT rescaled (1 mutez is treated as 1 wei); sending value is sp.send through `self.send_native`', uint256: 'sp.nat (arbitrary precision; Solidity overflow reverts above 2^256-1 are reproduced only where the body uses `u256`)', 'dynamic-bytes': 'bytes become sp.bytes', fallback: 'receive() becomes an explicit `deposit` entrypoint; there is no fallback entrypoint' } as Record<string, string>)[n.id] ?? n.detail }))];
  }

  design(spec: ContractSpec, opts: { decimals?: number }): TezosDesign { return buildDesign(spec, opts.decimals !== undefined ? { originalDecimals: opts.decimals } : {}); }

  templates(spec: ContractSpec, opts: { decimals?: number; facts?: TokenFacts }): TemplateResult<TezosDesign> | null {
    const v = classifyStandard(spec);
    // ERC-721: no FA2 NFT recipe in this pack (see README): it goes through the model path
    if (!v.match || v.match.standard !== 'ERC-20') return null;
    if (recipeFits(spec)) return null;
    const info = erc20Info(spec, v.match);
    const design = buildTemplateDesign(spec, info);
    return { design, files: recipeFiles(spec, info, design, opts.facts ?? {}), standard: v.match.standard, needsProgram: true, buildRun: (set) => buildTokenPlan({ spec, design, set }, info) };
  }

  units(design: TezosDesign): string[] { return design.instructions.filter((h) => !h.generated).map((h) => h.unit); }

  generatePrompt(ctx: GenerateContext<TezosDesign>, unit: string) {
    const h = ctx.design.instructions.find((x) => x.unit === unit)!;
    return { system: SYSTEM, user: handlerPrompt(ctx.spec, ctx.design, h, sourceLookup(ctx.sources)) };
  }

  /** model bodies -> normalised (mechanical rewrites) -> lint; lint problems go to cmc/lint.txt so `compile` can reject the project without a compiler round trip */
  assemble(spec: ContractSpec, design: TezosDesign, bodies: Record<string, string>) {
    const clean: Record<string, string> = {};
    const lintLines: string[] = [];
    for (const h of design.instructions) {
      const b = bodies[h.unit];
      if (b === undefined || h.generated) continue;
      const n = normaliseBody(b, { d: design, h, spec });
      clean[h.unit] = n.body;
      if (n.fixes.length) this.normalisations.set(h.unit, n.fixes); else this.normalisations.delete(h.unit);
      const issues = lintBody(n.body, h, design);
      if (issues.length) lintLines.push(section(h.unit, formatIssues(h.unit, issues)));
    }
    // report the mechanical rewrites honestly in the design notes (the note is replaced on every assemble)
    design.notes = design.notes.filter((x) => !x.startsWith('Mechanical normalisation'));
    if (this.normalisations.size) {
      const kinds = new Set([...this.normalisations.values()].flat().map((f) => ell(f.replace(/`[^`]*`/g, '`..`'), 90)));
      design.notes.push(`Mechanical normalisation: before compiling, code (not the model) rewrote constructs with exactly one meaning in ${this.normalisations.size} function body/bodies (${[...this.normalisations.keys()].join(', ')}); the rewrites are listed in NORMALISATIONS.md of the project and the bodies in contract_def.py are the rewritten ones. Kinds: ${more([...kinds], 6)}.`);
    }
    const files = genProject(spec, design, clean);
    if (lintLines.length) files['cmc/lint.txt'] = lintLines.join('\n');
    if (this.normalisations.size) files['NORMALISATIONS.md'] = ['# Mechanical rewrites applied to the model-written bodies', '', 'Before compiling, the pipeline rewrites constructs that have exactly one meaning in SmartPy 0.25 (code, no model). The bodies in `contract_def.py` are the rewritten ones.', '', ...[...this.normalisations.entries()].flatMap(([u, f]) => [`## ${u}`, ...f.map((x) => `- ${x}`), ''])].join('\n');
    return files;
  }

  async compile(files: Record<string, string>, onLog?: (s: string) => void): Promise<CompileResult> {
    const t0 = Date.now();
    const secs = () => (Date.now() - t0) / 1000;
    if (files['cmc/lint.txt']) return { ok: false, log: `=== LINT (static checks, no compiler round spent) ===\n${files['cmc/lint.txt']}`, seconds: secs(), artifacts: {} };
    const r = await runToolchain(this.container, 'compile', files, { wantOut: true, ...(onLog ? { onLog } : {}) });
    const artifacts: Record<string, Buffer> = {};
    if (r.out['contract.tz']) artifacts['contract.tz'] = r.out['contract.tz']!;
    if (r.out['storage.tz']) artifacts['storage.tz'] = r.out['storage.tz']!;
    if (r.code === 0 && artifacts['contract.tz']) {
      // the Michelson and the initial storage are part of the deliverable (compile receives the pipeline's own file map)
      files['michelson/contract.tz'] = artifacts['contract.tz'].toString('utf8');
      if (artifacts['storage.tz']) files['michelson/storage.tz'] = artifacts['storage.tz'].toString('utf8');
      return { ok: true, log: r.log, seconds: secs(), artifacts };
    }
    let log = `=== FULL ===\n${r.log}`;
    // one error per model-written unit: compile each unit alone (the others stubbed) in ONE more container run
    const def = files[DEF_FILE] ?? '';
    const blocks = parseUnits(def);
    if (blocks.length > 0 && !/Traceback[\s\S]*contract\.py[\s\S]*OSError/.test(r.log)) {
      const variants: Record<string, string> = {};
      const ranges = new Map<string, { s: number; e: number }>();
      for (const b of blocks) {
        const v = stubUnits(def, b.unit);
        variants[`cmc/variants/${b.unit}/${DEF_FILE}`] = v;
        const vb = parseUnits(v).find((x) => x.unit === b.unit)!;
        ranges.set(b.unit, { s: vb.startLine, e: vb.endLine });
      }
      const r2 = await runToolchain(this.container, 'compile', { ...files, ...variants }, { ...(onLog ? { onLog } : {}) });
      let other = false; let blamed = 0;
      for (const m of r2.log.matchAll(/^=== VARIANT (\w+) exit (\d+) ===\n([\s\S]*?)(?=^=== VARIANT |(?![\s\S]))/gm)) {
        if (m[2] === '0') continue;
        const rg = ranges.get(m[1]!)!;
        const lines = [...m[3]!.matchAll(/contract_def\.py(?:", line |:)(\d+)/g)].map((x) => Number(x[1]));
        if (lines.some((n) => n >= rg.s - 1 && n <= rg.e + 1)) { log += `\n${section(m[1]!, m[3]!)}`; blamed++; }
        else other = true;
      }
      if (!blamed || other) log += `\n=== OTHER ===\n(an error outside the model-written bodies: generated scaffolding or a cross-unit problem)\n`;
    } else if (blocks.length === 0) log += '\n=== OTHER ===\n(no model-written bodies)\n';
    return { ok: false, log, seconds: secs(), artifacts };
  }

  blame(log: string, _design: TezosDesign) {
    const units = new Set<string>();
    for (const m of log.matchAll(/^=== UNIT (\w+) ===$/gm)) units.add(m[1]!);
    return { units, other: /^=== OTHER ===$/m.test(log) || units.size === 0 };
  }

  repairPrompt(design: TezosDesign, unit: string, body: string, log: string) {
    const h = design.instructions.find((x) => x.unit === unit)!;
    const text = parseUnitSections(log).get(unit) ?? log.slice(-3000);
    return { system: SYSTEM, user: repairPrompt(h, body, text, hintsFor(text)) };
  }

  behaviourRepairPrompt(design: TezosDesign, unit: string, body: string, problems: string[]) {
    return { system: SYSTEM, user: behaviourRepairPrompt(design.instructions.find((x) => x.unit === unit)!, body, problems) };
  }

  unitOf(design: TezosDesign, fn: string): string | null {
    if (fn === 'receive') return design.instructions.find((h) => h.solidity === 'receive')?.unit ?? null;
    if (fn === 'constructor') return design.instructions.find((h) => h.kind === 'initialize')?.unit ?? null;
    const h = design.instructions.find((x) => x.solidity === fn && !x.generated);
    return h?.unit ?? null;
  }

  async runScenarios(files: Record<string, string>, _compiled: CompileResult, design: TezosDesign, spec: ContractSpec, set: ScenarioSet): Promise<ScenarioRun> {
    const t0 = Date.now();
    let built; let project: Record<string, string>;
    if (design.mode === 'template') {
      const t = this.templates(spec, {})!;
      built = t.buildRun(set) as ReturnType<typeof buildTokenPlan>;
      project = { ...files, 'cmc/plan.json': JSON.stringify(built.plan) };
    } else {
      built = buildProgramPlan({ spec, design, set });
      project = { ...files, [`${MOCK_MODULE}.py`]: genFa12Module(MOCK_INFO, { mock: true, moduleName: 'mock_token' }), 'cmc/plan.json': JSON.stringify(built.plan) };
      delete project['cmc/lint.txt'];
    }
    const r = await runToolchain(this.container, 'run-plan', project, {});
    const res = extractResult(r.log) as RunnerResult | null;
    if (!res) return { outcomes: [], seconds: (Date.now() - t0) / 1000, fatal: `the runner produced no result (exit ${r.code}): ${r.log.slice(-800)}`, conformance: [] };
    return { outcomes: compareResults(set, built, res), seconds: (Date.now() - t0) / 1000, conformance: [] };
  }

  deployCommands(design: TezosDesign, spec: ContractSpec): string[] {
    if (design.mode === 'template') return ['bash deploy-ghostnet.sh   # compiles with SmartPy (offline) and runs `octez-client originate contract ...`; needs octez-client and a funded Ghostnet account (not executed)'];
    const name = spec.name.toLowerCase();
    return [
      '# 1. Michelson and initial storage are in michelson/contract.tz and michelson/storage.tz (placeholder deployer: the tz1 burn address).',
      '#    Recompile with your own deployer address (offline, needs `pip install smartpy-tezos==0.25.3`): python3 contract.py <YOUR_tz1_ADDRESS>   -> compile/step_001_cont_0_contract.tz, compile/step_001_cont_0_storage.tz',
      '# 2. Ghostnet testnet origination (octez-client, funded Ghostnet account, alias ALICE):',
      'ENDPOINT=https://rpc.ghostnet.teztnets.com',
      `octez-client --endpoint $ENDPOINT originate contract ${name} transferring 0 from ALICE running compile/step_001_cont_0_contract.tz --init "$(cat compile/step_001_cont_0_storage.tz)" --burn-cap 5 --force`,
      ...(design.hasInitialize ? [`# 3. run the Solidity constructor: the deployer (the account named in the storage) calls initialize ONCE:`, `octez-client --endpoint $ENDPOINT transfer 0 from ALICE to ${name} --entrypoint initialize --arg '<Michelson value of the %initialize parameter (see its type in michelson/contract.tz): ${design.instructions.find((h) => h.kind === 'initialize')?.args.map((a) => `${a.name}: ${a.t.sp}`).join(', ') || 'Unit'}>' --burn-cap 1`, '#    (or from SmartPy: `contract.initialize(...)`; every other entrypoint refuses to run before initialize)'] : []),
      ...(design.tokens.length ? ['# token calls use FA1.2: the caller first approves this contract on the token: octez-client transfer 0 from ALICE to <TOKEN_KT1> --entrypoint approve --arg \'Pair "<THIS_CONTRACT_KT1>" <AMOUNT>\''] : []),
      `# ${spec.name}: not audited`,
    ];
  }
}
