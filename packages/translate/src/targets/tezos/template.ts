export interface Erc20Info {
  /** constructor parameter index of name / symbol / initial supply (-1 when absent) */
  nameParam: number; symbolParam: number; supplyParam: number | null;
  decimals: number;
  fixedName?: string; fixedSymbol?: string;
  mintable: boolean; burnable: boolean; ownable: boolean;
  increaseAllowance: boolean; decreaseAllowance: boolean; renounce: boolean;
  /** the original rejects address(0) as recipient/new owner (OpenZeppelin style) */
  zeroGuards: boolean;
  /** approve/increaseAllowance/decreaseAllowance reject address(0) as spender (OpenZeppelin `_approve`) */
  approveGuard: boolean;
}

const bare = (s: string) => s.replace(/^_+/, '').replace(/_+$/, '').toLowerCase();
const paramIndex = (spec: ContractSpec, stateVar: string): number => {
  const ps = spec.constructor?.params ?? [];
  const a = spec.constructor?.paramAssignments?.find((x) => bare(x.stateVar) === stateVar)?.param;
  if (a) return ps.findIndex((p) => p.name === a);
  return ps.findIndex((p) => p.type.kind === 'string' && bare(p.name) === stateVar);
};

export function erc20Info(spec: ContractSpec, m: StandardMatch): Erc20Info {
  const dec = Number(spec.stateVars.find((s) => s.name === 'decimals')?.initial?.value ?? 18);
  const has = (n: string) => spec.functions.some((f) => f.name === n && f.kind === 'function' && (f.visibility === 'public' || f.visibility === 'external'));
  const tr = spec.functions.find((f) => f.name === 'transfer');
  return {
    nameParam: paramIndex(spec, 'name'), symbolParam: paramIndex(spec, 'symbol'), supplyParam: m.initialSupplyParam, decimals: Number.isFinite(dec) ? dec : 18,
    mintable: m.features.mintable, burnable: m.features.burnable, ownable: m.features.ownable,
    increaseAllowance: has('increaseAllowance'), decreaseAllowance: has('decreaseAllowance'), renounce: has('renounceOwnership'),
    zeroGuards: !!tr?.requires.some((r) => /address\(0\)/.test(r.condition)),
    approveGuard: !!spec.functions.find((x) => x.name === 'approve')?.requires.some((r) => /address\(0\)/.test(r.condition)),
  };
}

/** can the FA1.2 recipe represent this ERC-20 (the entry signatures the recipe offers must equal the original's)? */
export function recipeFits(spec: ContractSpec): string | null {
  const f = (n: string) => spec.functions.find((x) => x.name === n && x.kind === 'function');
  const burn = f('burn'); if (burn && burn.params.length !== 1) return 'burn takes more than one parameter';
  const mint = f('mint'); if (mint && mint.params.length !== 2) return 'mint does not take (to, amount)';
  const to = f('transferOwnership'); if (to && to.params.length !== 1) return 'transferOwnership does not take one parameter';
  return null;
}

/** The FA1.2 (TZIP-7) ERC-20 recipe as SmartPy. Also used (with all optional entrypoints off) as the scenario mock token. */
export function genFa12Module(info: Erc20Info, opts: { mock?: boolean; moduleName?: string } = {}): string {
  const owner = info.ownable || info.mintable;
  const L: string[] = [];
  const A = (s = '') => L.push(s);
  A('# FA1.2 (TZIP-7) token with ERC-20 semantics. Generated by CloneMyContracts (Tezos pack). UNAUDITED.');
  A('# Difference from the SmartPy reference template: no administrator bypass in `transfer` (an owner cannot move other people\'s tokens), `approve` simply SETS the');
  A('# allowance like ERC-20 (no TZIP-7 "unsafe allowance change" guard), and an allowance of 2^256-1 is never decremented (OpenZeppelin >= 4 / the benchmark behaviour).');
  A('import smartpy as sp');
  A(''); A('');
  A('@sp.module'); A(`def ${opts.moduleName ?? 'main'}():`);
  A(`    ZERO_ADDRESS = sp.address("${ZERO_ADDRESS}")`);
  A(`    MAX_UINT256 = ${MAX_UINT256}`);
  A('');
  A('    class Token(sp.Contract):');
  A(`        def __init__(self, owner, supply, name, symbol, decimals, token_info):`);
  A('            self.data.owner = owner');
  A('            self.data.name = name');
  A('            self.data.symbol = symbol');
  A('            self.data.decimals = decimals');
  A('            self.data.total_supply = supply');
  A('            self.data.ledger = sp.cast(sp.big_map(), sp.big_map[sp.address, sp.nat])');
  A('            self.data.allowances = sp.cast(sp.big_map(), sp.big_map[sp.pair[sp.address, sp.address], sp.nat])');
  A('            self.data.token_metadata = sp.big_map({0: sp.record(token_id=0, token_info=token_info)})');
  A('            self.data.metadata = sp.cast(sp.big_map(), sp.big_map[sp.string, sp.bytes])');
  A('            if supply > 0:'); A('                self.data.ledger[owner] = supply');
  A('');
  // NOTE: SmartPy 0.25 private methods cannot call other private methods, so everything is inlined here
  A('        @sp.entrypoint'); A(`        def transfer(self, param: ${FA12_TRANSFER_T}):`);
  A('            if param.from_ != sp.sender:');
  A('                allowed = self.data.allowances.get((param.from_, sp.sender), default=sp.nat(0))');
  A('                if allowed != MAX_UINT256:'); A('                    assert allowed >= param.value, "allowance"'); A('                    self.data.allowances[(param.from_, sp.sender)] = sp.as_nat(allowed - param.value)');
  if (info.zeroGuards && !opts.mock) A('            assert param.to_ != ZERO_ADDRESS, "zero address"');
  A('            bal = self.data.ledger.get(param.from_, default=sp.nat(0))'); A('            assert bal >= param.value, "balance"');
  A('            self.data.ledger[param.from_] = sp.as_nat(bal - param.value)'); A('            self.data.ledger[param.to_] = self.data.ledger.get(param.to_, default=sp.nat(0)) + param.value'); A('');
  A('        @sp.entrypoint'); A(`        def approve(self, param: ${FA12_APPROVE_T}):`); if (info.approveGuard && !opts.mock) A('            assert param.spender != ZERO_ADDRESS, "approve to the zero address"'); A('            self.data.allowances[(sp.sender, param.spender)] = param.value'); A('');
  if (info.increaseAllowance) { A('        @sp.entrypoint'); A('        def increaseAllowance(self, spender: sp.address, value: sp.nat):'); if (info.approveGuard) A('            assert spender != ZERO_ADDRESS, "approve to the zero address"'); A('            self.data.allowances[(sp.sender, spender)] = self.data.allowances.get((sp.sender, spender), default=sp.nat(0)) + value'); A(''); }
  if (info.decreaseAllowance) { A('        @sp.entrypoint'); A('        def decreaseAllowance(self, spender: sp.address, value: sp.nat):'); if (info.approveGuard) A('            assert spender != ZERO_ADDRESS, "approve to the zero address"'); A('            self.data.allowances[(sp.sender, spender)] = sp.as_nat(self.data.allowances.get((sp.sender, spender), default=sp.nat(0)) - value, error="allowance")'); A(''); }
  if (info.mintable) {
    A('        @sp.entrypoint'); A('        def mint(self, to_: sp.address, value: sp.nat):'); A('            assert sp.sender == self.data.owner, "not owner"');
    if (info.zeroGuards && !opts.mock) A('            assert to_ != ZERO_ADDRESS, "zero address"');
    A('            self.data.total_supply += value'); A('            self.data.ledger[to_] = self.data.ledger.get(to_, default=sp.nat(0)) + value'); A('');
  }
  if (info.burnable) {
    A('        @sp.entrypoint'); A('        def burn(self, value: sp.nat):'); A('            bal = self.data.ledger.get(sp.sender, default=sp.nat(0))'); A('            assert bal >= value, "balance"');
    A('            self.data.ledger[sp.sender] = sp.as_nat(bal - value)'); A('            self.data.total_supply = sp.as_nat(self.data.total_supply - value)'); A('');
  }
  if (info.ownable) {
    A('        @sp.entrypoint'); A('        def transferOwnership(self, new_owner: sp.address):'); A('            assert sp.sender == self.data.owner, "not owner"');
    if (info.zeroGuards) A('            assert new_owner != ZERO_ADDRESS, "zero owner"');
    A('            self.data.owner = new_owner'); A('');
    if (info.renounce) { A('        @sp.entrypoint'); A('        def renounceOwnership(self):'); A('            assert sp.sender == self.data.owner, "not owner"'); A('            self.data.owner = ZERO_ADDRESS'); A(''); }
  }
  A('        @sp.entrypoint'); A('        def getBalance(self, param: sp.pair[sp.address, sp.contract[sp.nat]]):'); A('            sp.transfer(self.data.ledger.get(sp.fst(param), default=sp.nat(0)), sp.mutez(0), sp.snd(param))'); A('');
  A('        @sp.entrypoint'); A('        def getAllowance(self, param: sp.pair[sp.record(owner=sp.address, spender=sp.address), sp.contract[sp.nat]]):'); A('            (args, callback) = param'); A('            sp.transfer(self.data.allowances.get((args.owner, args.spender), default=sp.nat(0)), sp.mutez(0), callback)'); A('');
  A('        @sp.entrypoint'); A('        def getTotalSupply(self, param: sp.pair[sp.unit, sp.contract[sp.nat]]):'); A('            sp.transfer(self.data.total_supply, sp.mutez(0), sp.snd(param))'); A('');
  A('        @sp.onchain_view()'); A('        def get_balance(self, owner: sp.address):'); A('            return self.data.ledger.get(owner, default=sp.nat(0))'); A('');
  A('        @sp.onchain_view()'); A('        def get_allowance(self, owner: sp.address, spender: sp.address):'); A('            return self.data.allowances.get((owner, spender), default=sp.nat(0))'); A('');
  A('        @sp.onchain_view()'); A('        def get_total_supply(self):'); A('            return self.data.total_supply'); A('');
  A('        @sp.onchain_view()'); A('        def get_name(self):'); A('            return self.data.name'); A('');
  A('        @sp.onchain_view()'); A('        def get_symbol(self):'); A('            return self.data.symbol'); A('');
  A('        @sp.onchain_view()'); A('        def get_decimals(self):'); A('            return self.data.decimals'); A('');
  if (owner) { A('        @sp.onchain_view()'); A('        def get_owner(self):'); A('            return self.data.owner'); A(''); }
  while (L[L.length - 1] === '') L.pop();
  L.push('');
  return L.join('\n');
}

export function genFa12Scenario(info: Erc20Info, facts: TokenFacts = {}): string {
  const q = (x: string | undefined) => JSON.stringify(x ?? '<SET_TOKEN_NAME>');
  const nameDefault = facts.name !== undefined ? JSON.stringify(facts.name) : '"<SET_TOKEN_NAME>"';
  const symDefault = facts.symbol !== undefined ? JSON.stringify(facts.symbol) : '"<SET_TOKEN_SYMBOL>"';
  const supplyDefault = info.supplyParam === null ? '0' : facts.totalSupply ?? '-1';
  void q;
  return `# Compiles the FA1.2 token to Michelson: python3 contract.py [OWNER_ADDRESS] [SUPPLY]
# OWNER receives the initial supply (the ERC-20 constructor mints to msg.sender).
# NAME / SYMBOL / SUPPLY are the ORIGINAL token's values${facts.source ? ` (read from ${facts.source})` : ' (they could not be read from the source chain: placeholders <SET_...> / -1 that deploy-ghostnet.sh refuses; set TOKEN_NAME, TOKEN_SYMBOL, SUPPLY)'}.
import os
import sys
import smartpy as sp
from contract_def import main

OWNER = sys.argv[1] if len(sys.argv) > 1 else "${ZERO_ADDRESS}"
SUPPLY = int(sys.argv[2]) if len(sys.argv) > 2 else int(os.environ.get("SUPPLY", ${supplyDefault}))
NAME = os.environ.get("TOKEN_NAME", ${nameDefault})
SYMBOL = os.environ.get("TOKEN_SYMBOL", ${symDefault})
DECIMALS = ${facts.decimals ?? info.decimals}
if os.environ.get("CMC_DEPLOY") == "1" and (SUPPLY < 0 or "<SET_" in NAME or "<SET_" in SYMBOL):
    sys.exit("set TOKEN_NAME / TOKEN_SYMBOL / SUPPLY to the original token's values (they could not be read from the source chain)")
if SUPPLY < 0:
    SUPPLY = 0   # compile check only; a deployment refuses this (CMC_DEPLOY=1)


@sp.add_test()
def test():
    scenario = sp.test_scenario("compile")
    token_info = {
        "name": sp.scenario_utils.bytes_of_string(NAME),
        "symbol": sp.scenario_utils.bytes_of_string(SYMBOL),
        "decimals": sp.scenario_utils.bytes_of_string(str(DECIMALS)),
    }
    c = main.Token(owner=sp.address(OWNER), supply=SUPPLY, name=NAME, symbol=SYMBOL, decimals=DECIMALS, token_info=token_info)
    scenario += c
`;
}

export function buildTemplateDesign(spec: ContractSpec, info: Erc20Info): TezosDesign {
  const notes: string[] = [
    `${spec.name} is a plain ERC-20, so it is not rewritten by the model: it becomes a generated FA1.2 (TZIP-7) token contract (\`contract_def.py\`), the Tezos fungible-token standard that keeps the ERC-20 allowance model. No model-written code.`,
    'FA1.2 rather than FA2: FA2 (TZIP-12) replaces allowances by operators (an operator may move ANY amount of the owner\'s tokens) and adds token ids and batch transfers, which is a different trust model from ERC-20 approve/transferFrom. FA1.2 has `transfer(from, to, value)` (the sender spends an allowance when it is not `from`) and `approve(spender, value)`, so contracts that pull tokens with transferFrom port one to one. The cost: FA1.2 is the older standard (wallet/indexer support is better for FA2; FA1.2 is still widely supported).',
    'Entrypoints: `transfer(from_, to_, value)` serves both ERC-20 `transfer` (from = the caller) and `transferFrom`; `approve(spender, value)` SETS the allowance (no TZIP-7 "unsafe allowance change" guard); the standard callback entrypoints `getBalance`, `getAllowance`, `getTotalSupply` are included, and on-chain views `get_balance`, `get_allowance`, `get_total_supply`, `get_name`, `get_symbol`, `get_decimals`' + (info.mintable || info.ownable ? ', `get_owner`' : '') + ' give the synchronous reads ERC-20 has (a Tezos contract cannot call a view of another contract and use the result inline, but off-chain clients and `sp.view` can).',
    `Decimals: ${info.decimals} (a nat in the metadata; nat is arbitrary precision so the 18-decimal supply needs no rescaling and no narrowing).`,
    'The ERC-20 constructor (name, symbol, initial supply minted to msg.sender) becomes the initial storage: the originating account passes `owner` (= deployer), the supply, name, symbol and decimals; the supply is credited to `owner` at origination.',
    (info.zeroGuards || info.approveGuard) ? `Zero-address guards are kept (${[info.zeroGuards ? 'transfer/mint/transferOwnership' : '', info.approveGuard ? 'approve/increaseAllowance/decreaseAllowance' : ''].filter(Boolean).join(', ')} reject the tz1 burn address standing in for address(0)).` : 'The original has no zero-address guards on transfer; none are generated.',
    'An allowance of 2^256-1 is never decremented by transferFrom (OpenZeppelin >= 4 behaviour); other allowances are decremented and checked.',
    info.mintable ? 'Owner-only `mint(to_, value)` is kept.' : 'Not mintable: the supply is fixed.',
    info.burnable ? '`burn(value)` burns the caller\'s own tokens.' : 'Not burnable.',
    info.ownable ? '`transferOwnership` (and `renounceOwnership` when present) keep the single owner role; `owner` is a plain address (the burn address after renouncing).' : 'No owner role.',
    'FA1.2 `transfer` makes no hook call to the receiver (like ERC-20, unlike ERC-777).',
    'Events: the Solidity Transfer / Approval / OwnershipTransferred events are NOT emitted (TZIP-7 defines none; indexers follow the operations and big_map updates). The behaviour check compares call results and state reads, not events.',
    'No `permit` (EIP-2612) and no return values: FA1.2 entrypoints return nothing.',
  ];
  return {
    version: 1, mode: 'template', contractName: spec.name, className: 'Token', decimals: { original: info.decimals, target: info.decimals, divisor: '1' },
    integerPolicy: ['FA1.2 balances, allowances and supply are nats (arbitrary precision): the original uint256 amounts are used as they are.'],
    native: { used: false }, hasSigned: false, hasInitialize: false, state: [], structs: [], tokens: [], instructions: [], observables: {}, constants: [], helpers: [],
    decimalsNote: `Decimals: the FA1.2 token keeps the original ${info.decimals} decimals (nat balances, no rescaling).`,
    allowanceNote: 'approve sets the allowance; transferFrom is FA1.2 transfer(from, to, value) by the spender, which spends the allowance exactly like ERC-20 (an allowance of 2^256-1 is not decremented)',
    notTranslated: [
      { feature: 'zero-address checks', where: info.zeroGuards ? 'none' : 'transfer', reason: 'Tezos has no zero address; the tz1 burn address is used as a stand-in where the original guards address(0)' },
      { feature: 'return values', where: 'transfer, approve, transferFrom', reason: 'FA1.2 entrypoints return nothing (ERC-20 returns bool); a failure aborts the transaction' },
    ].filter((x) => x.where !== 'none'),
    notes,
  };
}

export function recipeFiles(spec: ContractSpec, info: Erc20Info, d: TezosDesign, facts: TokenFacts = {}): Record<string, string> {
  return {
    'contract_def.py': genFa12Module(info),
    'contract.py': genFa12Scenario(info, facts),
    'token.json': JSON.stringify({ standard: 'ERC-20', target: 'FA1.2 (TZIP-7)', decimals: info.decimals, features: { mintable: info.mintable, burnable: info.burnable, ownable: info.ownable }, notes: d.notes.slice(0, 3) }, null, 2) + '\n',
    'deploy-ghostnet.sh': deployScript(spec),
  };
}

const deployScript = (spec: ContractSpec) => `#!/usr/bin/env bash
# Originate ${spec.name} (FA1.2 token) on Ghostnet. NOT executed by CloneMyContracts. Needs octez-client with a funded Ghostnet account.
# 1. compile (offline): python3 contract.py <YOUR_tz1_ADDRESS> <INITIAL_SUPPLY>   (writes ./compile/step_001_cont_0_contract.tz and _storage.tz)
# 2. originate:
set -euo pipefail
ALIAS=\${ALIAS:?your octez-client alias (the owner who receives the supply)}
OWNER=$(octez-client show address "$ALIAS" | sed -n 's/^Hash: //p')
export CMC_DEPLOY=1
python3 contract.py "$OWNER" \${SUPPLY:+"$SUPPLY"}   # SUPPLY / TOKEN_NAME / TOKEN_SYMBOL override the original token's values read from the source chain; unset placeholders make this fail
octez-client --endpoint "\${ENDPOINT:-https://rpc.ghostnet.teztnets.com}" originate contract ${spec.name.toLowerCase()} transferring 0 from "$ALIAS" \\
  running compile/step_001_cont_0_contract.tz --init "$(cat compile/step_001_cont_0_storage.tz)" --burn-cap 2 --force
`;
