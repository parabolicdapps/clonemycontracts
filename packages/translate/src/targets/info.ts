import type { TargetPack } from './pack.js';

/** What a UI needs to describe a rewrite target, taken from the pack itself. */
export interface TargetInfo {
  id: string;
  label: string;
  language: string;
  /** what a plain ERC-20 becomes (the template path, no model-written code) */
  nativeStandard: string;
  /** what the behaviour check runs the rewrite on */
  runtime: string;
  /** what the model path produces */
  modelPath: string;
  deployTitle: string;
}

/** Wording of the Solana pack (it has no `reportLabels`; the report falls back to these). */
const SOLANA_WORDING = {
  runtime: 'a local Solana runtime (litesvm)',
  template: 'native SPL token',
  model: 'model-generated Anchor program (accounts, state, events and errors are generated by code; the model wrote the instruction bodies)',
  deployTitle: 'Deploy to devnet',
};

export function describeTarget(pack: TargetPack): TargetInfo {
  const l = pack.reportLabels ?? SOLANA_WORDING;
  return { id: pack.id, label: pack.label, language: pack.language ?? pack.label, nativeStandard: l.template, runtime: l.runtime, modelPath: l.model, deployTitle: l.deployTitle };
}

