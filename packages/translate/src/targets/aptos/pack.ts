import type { ContractSpec, ScenarioSet, TokenFacts } from '../../types.js';
import { classifyStandard } from '../../spec/standard.js';
import { DEFAULT_CONTAINER, runToolchain, type ContainerConfig } from '../../pipeline/container.js';
import type { CompileResult, GenerateContext, ScenarioRun, TargetPack, TemplateResult } from '../pack.js';
import { buildTestPlan, parseTestOutput } from './adapter.js';
import { annotateLog, assembleAptos, genMoveToml } from './codegen.js';
import { compareResults } from './compare.js';
import { buildAptosDesign } from './design.js';
import type { AptosDesign } from './design-types.js';
import { SYSTEM, behaviourRepairPrompt, failingUnits, firstErrorBlocks, hintsFor, instructionPrompt, repairPrompt, sourceLookup, errorBlocks } from './prompts.js';
import { buildTemplateDesign, templateApplies, templateFiles } from './template.js';
import { buildNftDesign, nftFiles } from './template-nft.js';

export const APTOS_CONTAINER: ContainerConfig = { ...DEFAULT_CONTAINER, image: process.env.CMC_APTOS_IMAGE ?? 'cmc-toolchain-aptos:0.2', concurrency: 2, cpus: 4 };

export class AptosPack implements TargetPack<AptosDesign> {
  readonly id = 'aptos';
  readonly label = 'Aptos (Move 2, framework 9.6)';
  readonly language = 'Move (Aptos)';
  readonly reportLabels = { runtime: 'the Move unit-test VM (aptos move test, offline)', template: 'Aptos Fungible Asset module, no model-written code', model: 'model-generated Move module (State, structs, events, error codes, helpers and signatures are generated by code; the model wrote the function bodies)', deployTitle: 'Publish to Aptos devnet/testnet (not executed by this pipeline)' };
  constructor(private container: ContainerConfig = APTOS_CONTAINER) {}

  design(spec: ContractSpec, opts: { decimals?: number }): AptosDesign { return buildAptosDesign(spec, { decimals: opts.decimals ?? 8 }); }

  templates(spec: ContractSpec, opts: { decimals?: number; facts?: TokenFacts }): TemplateResult<AptosDesign> | null {
    const v = classifyStandard(spec);
    if (v.match?.standard === 'ERC-721') { const d = buildNftDesign(spec, v.match, 0, opts.decimals ?? 8); return { design: d, files: nftFiles(), standard: 'ERC-721', needsProgram: true, buildRun: () => null }; }
    if (!v.match || templateApplies(spec, v.match) !== null) return null;
    const origDec = opts.facts?.decimals ?? Number(spec.stateVars.find((s) => s.name === 'decimals')?.initial?.value ?? 18);
    const design = buildTemplateDesign(spec, v.match, origDec, opts.decimals ?? 8);
    if (opts.facts && Object.keys(opts.facts).length) design.facts = opts.facts;
    return { design, files: templateFiles(design), standard: v.match.standard, needsProgram: true, buildRun: () => null };
  }

  describeNonPortable(spec: ContractSpec): ContractSpec['nonPortable'] {
    return spec.nonPortable.map((n) => {
      if (n.id === 'low-level-call') return { ...n, treatment: 'flagged' as const, detail: 'Value-only low-level calls (`call{value: v}("")`, `transfer`, `send`) are translated with `native_push`; the calldata of a call that carries data, and calls without value, are NOT (Move has no dynamic dispatch).' };
      if (n.id === 'native-value') return { ...n, treatment: 'mapped' as const, detail: 'ETH value becomes APT octas (8 decimals): `msg.value` is an explicit `value: u256` argument that the generated prologue moves from the caller to the contract (aptos_account::transfer); payouts use `native_push`.' };
      if (n.id === 'uint256') return { ...n, treatment: 'mapped' as const, detail: 'uint256 stays u256 (all widths are kept). Only framework amounts (fungible-asset and APT transfers) are u64, inside the generated helpers: a larger amount aborts instead of wrapping.' };
      return n;
    });
  }

  units(design: AptosDesign): string[] { return design.instructions.map((i) => i.name); }

  generatePrompt(ctx: GenerateContext<AptosDesign>, unit: string) {
    const ins = ctx.design.instructions.find((i) => i.name === unit)!;
    return { system: SYSTEM, user: instructionPrompt(ctx.spec, ctx.design, ins, sourceLookup(ctx.sources)) };
  }

  assemble(spec: ContractSpec, design: AptosDesign, bodies: Record<string, string>) { return assembleAptos(spec, design, bodies); }

  async compile(files: Record<string, string>, onLog?: (s: string) => void): Promise<CompileResult> {
    const r = await runToolchain(this.container, 'compile', files, { ...(onLog ? { onLog } : {}) });
    return { ok: r.code === 0, log: annotateLog(r.log, files), seconds: r.seconds, artifacts: {} };
  }

  blame(log: string, design: AptosDesign) { const f = failingUnits(log, design); return { units: f.units, other: f.other || f.units.size === 0 }; }

  repairPrompt(design: AptosDesign, unit: string, body: string, log: string) {
    const ins = design.instructions.find((i) => i.name === unit)!;
    const mine = errorBlocks(log).filter((b) => b.includes(`[unit ${unit}]`));
    const text = mine.length ? mine.slice(0, 4).join('\n\n') : firstErrorBlocks(log, 4, 5000);
    return { system: SYSTEM, user: repairPrompt(design, ins, body, text, hintsFor(text)) };
  }

  behaviourRepairPrompt(design: AptosDesign, unit: string, body: string, problems: string[]) {
    return { system: SYSTEM, user: behaviourRepairPrompt(design, design.instructions.find((i) => i.name === unit)!, body, problems) };
  }

  unitOf(design: AptosDesign, fn: string): string | null {
    if (fn === 'receive') return design.instructions.find((i) => i.kind === 'receive')?.name ?? null;
    if (fn === 'constructor') return 'initialize';
    return design.instructions.find((i) => i.solidity === fn)?.name ?? null;
  }

  async runScenarios(files: Record<string, string>, _compiled: CompileResult, design: AptosDesign, _spec: ContractSpec, set: ScenarioSet): Promise<ScenarioRun> {
    const t0 = Date.now();
    if (design.template?.standard === 'ERC-721') return { outcomes: set.scenarios.map((sc) => ({ id: sc.id, title: sc.title, kind: sc.kind, ...(sc.fn ? { fn: sc.fn } : {}), status: 'not-runnable' as const, mismatches: [], notRunnable: ['ERC-721 recipe: compiled but not executed (token ids are object addresses on Aptos)'], checked: 0, notes: [] })), seconds: 0, conformance: [] };
    const plan = buildTestPlan({ design, set });
    const project = { ...files, 'tests/cmc_tests.move': plan.source };
    const r = await runToolchain(this.container, 'test', project);
    const parsed = parseTestOutput(r.log);
    if (parsed.compileError || parsed.results.size === 0) {
      return { outcomes: [], seconds: (Date.now() - t0) / 1000, fatal: `the test run produced no results (exit ${r.code}): ${firstErrorBlocks(annotateLog(r.log, project), 3, 1500) || r.log.slice(-800)}`, conformance: [] };
    }
    return { outcomes: compareResults(set, plan, parsed.results, design), seconds: (Date.now() - t0) / 1000, conformance: [] };
  }

  deployCommands(design: AptosDesign, spec: ContractSpec): string[] {
    const init = design.instructions.find((i) => i.kind === 'initialize');
    // template: the ORIGINAL token's name / symbol / supply (read from the source chain) or shell placeholders that fail when unset; never test values
    const f = design.facts;
    let strIdx = 0;
    const args = (init?.params ?? []).map((p) => {
      if (design.mode === 'template' && p.move === 'String') { const isName = strIdx++ === 0; const v = isName ? f?.name : f?.symbol; const nm = isName ? 'TOKEN_NAME' : 'TOKEN_SYMBOL'; return `string:${v !== undefined ? JSON.stringify(v) : `"\${${nm}:?set ${nm} to the original token's ${isName ? 'name' : 'symbol'}}"`}`; }
      if (design.mode === 'template' && p.scale === 'token' && p.name === 'initial_supply') { const orig = design.decimals.original, dec = design.decimals.aptos; const q = f?.totalSupply !== undefined ? (BigInt(f.totalSupply) / 10n ** BigInt(Math.max(0, orig - dec))).toString() : null; return `u64:${q ?? `"\${SUPPLY:?set SUPPLY to the original total supply in base units at ${dec} decimals}"`}`; }
      return `${p.move === 'String' ? 'string' : p.move}:<${p.name}>`;
    }).join(' ');
    return [
      '# one-off: install the Aptos CLI (https://aptos.dev/tools/aptos-cli/), then',
      'aptos init --network devnet            # creates a key pair and funds it from the devnet faucet (testnet: --network testnet + faucet page)',
      'aptos move compile --named-addresses app=default',
      'aptos move publish --named-addresses app=default --assume-yes',
      `aptos move run --function-id default::${design.moduleName}::initialize ${args ? `--args ${args}` : ''}   # once; only the publishing account may call it`,
      design.mode === 'program' ? `# State lives at the resource account derived from your account and the seed "cmc_state": aptos account derive-resource-account-address --address default --seed cmc_state` : '# the asset metadata object is at: aptos account derive-object-address --address default --object-creation-seed CMC_TOKEN (check with aptos CLI help)',
      `# ${spec.name}: not audited. Nothing above was executed by the rewrite pipeline.`,
    ];
  }
}
