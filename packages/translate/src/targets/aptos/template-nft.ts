import type { ContractSpec } from '../../types.js';
import type { StandardMatch } from '../../spec/standard.js';
import type { AptosDesign, InstructionDesign, ParamDesign } from './design-types.js';
import { ident } from './names.js';
import { genMoveToml } from './codegen.js';

/**
 * Plain ERC-721 -> Aptos Digital Asset (aptos_token_objects: a collection and token objects) recipe. It is compiled in the sandbox but its
 * behaviour is NOT executed by the pipeline (the scenario format has token ids, Aptos has object addresses), so the result is UNVERIFIED by design.
 */
export function buildNftDesign(spec: ContractSpec, m: StandardMatch, origDec: number, aptDec: number): AptosDesign {
  const params: ParamDesign[] = (spec.constructor?.params ?? []).map((p, i) => ({ name: ident(p.name), move: p.type.kind === 'string' ? 'String' : p.type.kind === 'uint' ? 'u64' : p.type.kind === 'address' ? 'address' : 'u64', solidity: p.type.solidity, scale: 'plain' as const, src: i }));
  const ins = (name: string, solidity: string, ps: ParamDesign[], kind: InstructionDesign['kind'] = 'entry'): InstructionDesign => ({ name, solidity, kind, params: ps, returns: [], payable: false, emits: [], requires: [], writes: [], uses: [], notes: [] });
  const instructions = [ins('initialize', 'constructor', params, 'initialize'), ins('mint', 'mint', [{ name: 'to', move: 'address', solidity: 'address', scale: 'plain', src: 0 }]), ins('transfer', 'transferFrom', [{ name: 'token', move: 'address', solidity: 'uint256', scale: 'plain', src: 0 }, { name: 'to', move: 'address', solidity: 'address', scale: 'plain', src: 1 }])];
  return {
    version: 1, mode: 'template', packageName: 'app', moduleName: 'nft', decimals: { original: origDec, aptos: aptDec, divisor: '1' }, integerPolicy: ['Token ids become object addresses.'],
    structs: [], scalars: [], constants: [], tables: [], arrays: [], tokens: [], usesNative: false, events: [], errors: [], helpers: [], instructions, observables: {}, notTranslated: [
      { feature: 'ERC-721 approvals', where: 'approve, getApproved, setApprovalForAll, isApprovedForAll', reason: 'Aptos objects have one owner and ungated transfer; per-token approvals and operators are not part of Digital Asset' },
      { feature: 'sequential token ids', where: 'tokenId', reason: 'tokens are objects with addresses, not integers' },
    ],
    notes: [
      `${m.standard} becomes an Aptos Digital Asset collection (aptos_token_objects) with one token object per mint. This is a RECIPE: it is compiled by the sandbox but its behaviour is not executed or compared with the original (token ids vs object addresses), so the report says UNVERIFIED.`,
      'Approvals (approve / setApprovalForAll) have no counterpart: an Aptos object is moved by its owner with `object::transfer`.',
    ],
    droppedFns: [], template: { standard: 'ERC-721', features: m.features, ctor: [] },
  };
}

export function genNftModule(): string {
  return `// Generated by cmc (Aptos pack, ERC-721 recipe): a plain ERC-721 as an Aptos Digital Asset collection. Compiled, NOT executed. Unaudited.
module app::nft {
    use std::option;
    use std::signer;
    use std::string::{Self, String};
    use aptos_framework::object::{Self, Object};
    use aptos_token_objects::collection;
    use aptos_token_objects::token::{Self, Token};

    const E_NOT_OWNER: u64 = 1;
    const E_NOT_PUBLISHER: u64 = 2;

    /// stored at the publisher (@app)
    struct Registry has key {
        owner: address,
        collection_name: String,
        base_uri: String,
        next_id: u64,
    }

    /// Creates the collection (unlimited supply; pass max_supply > 0 for a fixed one).
    public entry fun initialize(caller: &signer, name: String, symbol: String, base_uri: String, max_supply: u64) {
        assert!(signer::address_of(caller) == @app, E_NOT_PUBLISHER);
        if (max_supply > 0) {
            collection::create_fixed_collection(caller, symbol, max_supply, name, option::none(), base_uri);
        } else {
            collection::create_unlimited_collection(caller, symbol, name, option::none(), base_uri);
        };
        move_to(caller, Registry { owner: signer::address_of(caller), collection_name: name, base_uri, next_id: 1 });
    }

    /// owner-only mint: creates a token object and hands it to \`to\`
    public entry fun mint(caller: &signer, to: address) acquires Registry {
        let r = borrow_global_mut<Registry>(@app);
        assert!(signer::address_of(caller) == r.owner, E_NOT_OWNER);
        let id = r.next_id;
        r.next_id = id + 1;
        let uri = r.base_uri;
        string::append(&mut uri, aptos_std::string_utils::to_string(&id));
        let cref = token::create(caller, r.collection_name, string::utf8(b""), aptos_std::string_utils::to_string(&id), option::none(), uri);
        let obj = object::object_from_constructor_ref<Token>(&cref);
        object::transfer(caller, obj, to);
    }

    /// move a token you own (the token object's address is in the mint transaction's events)
    public entry fun transfer(owner: &signer, token: address, to: address) {
        object::transfer(owner, object::address_to_object<Token>(token), to);
    }

    #[view]
    public fun owner_of(token: address): address {
        object::owner(object::address_to_object<Token>(token))
    }
}
`;
}

export function nftFiles(): Record<string, string> {
  return { 'Move.toml': genMoveToml().replace('[dependencies]\n', '[dependencies]\nAptosTokenObjects = { local = "/opt/aptos-framework/aptos-token-objects" }\n'), 'sources/nft.move': genNftModule() };
}
