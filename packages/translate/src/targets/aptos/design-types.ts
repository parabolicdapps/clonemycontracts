export type Scale = 'token' | 'plain' | 'ratio';

/** A Move type as written in source, plus what it came from. */
export interface MoveField {
  name: string;
  move: string;
  solidity: string;
  scale: Scale;
  note?: string;
}

/** User struct (from a Solidity struct) or a generated composite mapping key. */
export interface StructDesign {
  name: string;
  role: 'struct' | 'key';
  fields: MoveField[];
  /** abilities computed by code from the field types */
  abilities: string[];
}

export interface TableDesign {
  /** Solidity mapping variable */
  solidity: string;
  /** Move field in State */
  field: string;
  /** key parameters of the accessors (one per mapping level) */
  keys: { name: string; move: string; solidity: string }[];
  /** the Move key type of the Table (a composite key struct for nested mappings) */
  tableKey: string;
  value: { move: string; solidity: string; scale: Scale; struct?: string };
}

export interface ArrayDesign {
  solidity: string;
  field: string;
  element: { move: string; solidity: string; scale: Scale; struct?: string };
  /** fixed length (`address[3]`), or null for a dynamic array */
  fixed: number | null;
}

export interface ScalarDesign extends MoveField {
  /** Solidity state variable */
  solidity: string;
  /** field name in State */
  field: string;
  immutable: boolean;
  isString: boolean;
  /** Move literal of the inline initialiser (evaluated by code; applied in the State literal of `initialize`) */
  init?: string;
  initShown?: string;
}

export interface TokenDesign {
  /** Solidity state variable / constructor parameter */
  solidity: string;
  /** helper name prefix (`token`, `staking_token`) */
  key: string;
  /** State field holding the fungible-asset metadata address */
  field: string;
  methods: string[];
}

export interface ConstDesign { solidity: string; name: string; move: string; value: string; scale: Scale; public: boolean }

export interface EventDesign { name: string; fields: MoveField[] }
export interface ErrorDesign { name: string; code: number; source: string }

export interface HelperDesign {
  name: string;
  /** full Move signature (without body), shown to the model */
  signature: string;
  doc: string;
  /** reads the State resource (so a function calling it needs `acquires State`) */
  acquires: boolean;
  /** Solidity state variable (or token / native) it belongs to; used to restrict the cheat sheet per function */
  group: string;
  /** the Move source of the helper (generated by code, never written by the model) */
  code: string;
}

export interface ParamDesign { name: string; move: string; solidity: string; scale: Scale | 'time'; /** index of the Solidity parameter; -1 for the synthetic `value` */ src: number; note?: string }

export interface InstructionDesign {
  /** Move function name */
  name: string;
  solidity: string;
  kind: 'initialize' | 'entry' | 'view' | 'receive';
  params: ParamDesign[];
  /** Move return type(s) of a view / entry (entries return nothing) */
  returns: { move: string; solidity: string; scale: Scale }[];
  payable: boolean;
  emits: string[];
  requires: string[];
  writes: string[];
  /** state groups (helper `group`) the cheat sheet shows for this function */
  uses: string[];
  notes: string[];
}

export type ObservableDesign =
  | { kind: 'view'; fn: string; scales: Scale[]; params: string[] }
  | { kind: 'token-balance' }
  | { kind: 'native-balance' }
  | { kind: 'unobservable'; reason: string };

export interface AptosDesign {
  version: 1;
  mode: 'program' | 'template';
  packageName: 'app';
  moduleName: string;
  /** decimals of the fungible assets used by fixtures, and the divisor from the original's base units */
  decimals: { original: number; aptos: number; divisor: string; solana?: never };
  integerPolicy: string[];
  structs: StructDesign[];
  scalars: ScalarDesign[];
  constants: ConstDesign[];
  tables: TableDesign[];
  arrays: ArrayDesign[];
  tokens: TokenDesign[];
  usesNative: boolean;
  events: EventDesign[];
  errors: ErrorDesign[];
  helpers: HelperDesign[];
  instructions: InstructionDesign[];
  observables: Record<string, ObservableDesign>;
  notTranslated: { feature: string; where: string; reason: string }[];
  notes: string[];
  /** Solidity functions this design deliberately does not have (documented differences), e.g. approve/transferFrom on Aptos fungible assets */
  droppedFns?: { fn: string; reason: string }[];
  /** template: the original token's facts read from the source chain (deploy arguments); absent = shell placeholders that fail when unset */
  facts?: { name?: string; symbol?: string; decimals?: number; totalSupply?: string; source?: string };
  /** template-only wording used by the report */
  allowanceNote?: string;
  decimalsNote?: string;
  /** template: standard and features */
  template?: { standard: 'ERC-20' | 'ERC-721'; features: { mintable: boolean; burnable: boolean; ownable: boolean }; ctor: { name: string; kind: 'string' | 'supply' | 'other' }[] };
}
